func TestPrunedSourceGeneratesThePrunedTable( t *testing.T ) {
	// What prune.py leaves of the table must be what the pruned source
	// generates: the markers sit on lines of their own, or at a line's end.
	pruned := func( text string , removed string ) ( result string ) {
		lines := []string{}
		depth := 0
		for _ , line := range strings.Split( markers( text ) , "\n" ) {
			switch {
			case strings.Contains( line , ">>> feature:" + removed ):
				depth++
				continue
			case strings.Contains( line , "<<< feature:" + removed ):
				depth--
				continue
			case depth > 0 || strings.HasSuffix( line , "// feature:" + removed ) || strings.Contains( line , "whole-file feature:" ):
				continue
			case strings.Contains( line , ">>> feature:" ) || strings.Contains( line , "<<< feature:" ):
				continue
			}
			line = strings.TrimRight( strings.Split( line , " // feature:" )[ 0 ] , " " )
			lines = append( lines , line )
		}
		result = strings.Join( lines , "\n" )
		return
	}
	for _ , removed := range []string{ "beta" , "mcp" } {
		dir := fixture( t , map[string]string{
			"server/routes/users.go":  pruned( fixtureUsers , removed ),
			"server/routes/routes.go": pruned( fixtureRoutes , removed ),
		} )
		source , err := Generate( dir )
		if err != nil { t.Fatal( err ) }
		if want := pruned( wantGenerated , removed ); string( source ) != want {
			t.Errorf( "without %s, generated:\n%s\nwant:\n%s" , removed , source , want )
		}
	}
}

