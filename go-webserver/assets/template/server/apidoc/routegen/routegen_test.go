// fixture writes a module with the routes package given, and answers the
// package's directory.
func fixture( t *testing.T , files map[string]string ) ( dir string ) {
	t.Helper()
	root := t.TempDir()
	all := map[string]string{
		"go.mod":                    "module example.com/app\n\ngo 1.26\n",
		"server/apidoc/apidoc.go":   "package apidoc\n\ntype None struct{}\n",
		"server/mcp/mcp.go":         "package mcp\n\ntype Server struct{}\n",
		"server/models/models.go":   fixtureModels,
		"server/routes/routes.go":   fixtureRoutes,
	}
	for name , text := range files { all[ name ] = text }
	for name , text := range all {
		path := filepath.Join( root , filepath.FromSlash( name ) )
		if err := os.MkdirAll( filepath.Dir( path ) , 0o755 ); err != nil { t.Fatal( err ) }
		if err := os.WriteFile( path , []byte( markers( text ) ) , 0o644 ); err != nil { t.Fatal( err ) }
	}
	dir = filepath.Join( root , "server" , "routes" )
	return
}

