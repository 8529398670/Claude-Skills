func TestTheMostSpecificPathComesFirst( t *testing.T ) {
	cases := []struct{ first , second string }{
		{ "/a/b" , "/a/{x}" },
		{ "/a/{x}/b" , "/a/{x}/{y}" },
		{ "/a" , "/a/b" },
		{ "/a/b" , "/a/c" },
	}
	for _ , test := range cases {
		a , b := mounted{ method: "GET" , path: test.first } , mounted{ method: "GET" , path: test.second }
		if before( a , b ) == false || before( b , a ) {
			t.Errorf( "%s should come before %s" , test.first , test.second )
		}
	}
	if ambiguous( mounted{ method: "GET" , path: "/a/b" } , mounted{ method: "GET" , path: "/a/{x}" } ) {
		t.Error( "a literal and a parameter in one place are not ambiguous: the literal wins" )
	}
	if ambiguous( mounted{ method: "GET" , path: "/a/{x}" } , mounted{ method: "POST" , path: "/a/{y}" } ) {
		t.Error( "two methods never clash" )
	}
	if ambiguous( mounted{ method: "GET" , path: "/a/{x}" } , mounted{ method: "GET" , path: "/a/{y}" } ) == false {
		t.Error( "two parameters in one place clash" )
	}
}
