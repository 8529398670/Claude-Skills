// The fixtures write their feature markers as FEATURE:, made feature: as
// they are written out, so scripts/prune.py never takes them for the
// template's own.
func markers( text string ) ( result string ) {
	result = strings.ReplaceAll( text , "FEATURE:" , "feature:" )
	return
}

