// The feature markers of scripts/prune.py, which cuts a route's entry with
// its handler.
var featureExpression = `!?[a-z0-9_]+(?:\|!?[a-z0-9_]+)*`
var wholeFileMarker = regexp.MustCompile( `whole-file feature:(` + featureExpression + `)` )
var blockStart = regexp.MustCompile( `>>> feature:(` + featureExpression + `)` )
var blockEnd = regexp.MustCompile( `<<< feature:(` + featureExpression + `)` )
var lineMarker = regexp.MustCompile( `[ \t]*//[ \t]*feature:(` + featureExpression + `)[ \t]*$` )
var featureName = regexp.MustCompile( `^` + featureExpression + `$` )
var specParameter = regexp.MustCompile( `^\{([A-Za-z_][A-Za-z0-9_]*)\}$` )
var toolName = regexp.MustCompile( `^[a-z][a-z0-9_]*$` )

