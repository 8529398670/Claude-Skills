func ( found *problems ) add( file string , line int , format string , args ...any ) {
	found.list = append( found.list , fmt.Sprintf( "%s:%d: " , file , line ) + fmt.Sprintf( format , args... ) )
}

// Generate reads the package in dir and answers the file it declares.
func Generate( dir string ) ( source []byte , err error ) {
	pkg , err := load( dir )
	if err != nil { return }
	found := &problems{}
	routes := pkg.routes( found )
	switches := pkg.featureSwitches()
	for _ , declared := range routes {
		pkg.check( declared , found )
	}
	ordered := order( routes , found )
	if len( found.list ) > 0 {
		sort.Strings( found.list )
		err = fmt.Errorf( "%s" , strings.Join( found.list , "\n" ) )
		return
	}
	source = pkg.write( ordered , routes , switches , found )
	if len( found.list ) > 0 {
		source = nil
		err = fmt.Errorf( "%s" , strings.Join( found.list , "\n" ) )
	}
	return
}

// The package being read.

type pkg struct {
	dir        string
	fset       *token.FileSet
	files      map[string]*ast.File
	text       map[string][]string
	names      []string
	module     string
	moduleDir  string
	external   map[string]*external
	generating string // the file with the //go:generate line
}

type external struct {
	pkgRef *pkg
}

type typeSpec struct {
	spec *ast.TypeSpec
	file *ast.File
	pkg  *pkg
	dir  string
}

func load( dir string ) ( loaded *pkg , err error ) {
	loaded = &pkg{ dir: dir , fset: token.NewFileSet() , files: map[string]*ast.File{} , text: map[string][]string{} , external: map[string]*external{} }
	entries , err := os.ReadDir( dir )
	if err != nil { return }
	for _ , entry := range entries {
		name := entry.Name()
		if entry.IsDir() || strings.HasSuffix( name , ".go" ) == false || strings.HasSuffix( name , "_test.go" ) || name == FileName { continue }
		raw , read_err := os.ReadFile( filepath.Join( dir , name ) )
		if read_err != nil {
			err = read_err
			return
		}
		file , parse_err := parser.ParseFile( loaded.fset , name , raw , parser.ParseComments )
		if parse_err != nil {
			err = parse_err
			return
		}
		loaded.files[ name ] = file
		loaded.text[ name ] = strings.Split( string( raw ) , "\n" )
		loaded.names = append( loaded.names , name )
		if bytes.Contains( raw , []byte( "//go:generate go run" ) ) && bytes.Contains( raw , []byte( "apidoc/gen" ) ) { loaded.generating = name }
	}
	sort.Strings( loaded.names )
	if len( loaded.names ) == 0 {
		err = fmt.Errorf( "%s: no Go files" , dir )
		return
	}
	if loaded.generating == "" {
		err = fmt.Errorf( "%s: no file has the //go:generate go run .../apidoc/gen line" , dir )
		return
	}
	loaded.module , loaded.moduleDir = findModule( dir )
	return
}

func findModule( dir string ) ( module string , module_dir string ) {
	current , err := filepath.Abs( dir )
	if err != nil { return }
	for {
		raw , read_err := os.ReadFile( filepath.Join( current , "go.mod" ) )
		if read_err == nil {
			for _ , line := range strings.Split( string( raw ) , "\n" ) {
				if rest , ok := strings.CutPrefix( strings.TrimSpace( line ) , "module " ); ok {
					module , module_dir = strings.Trim( strings.TrimSpace( rest ) , `"` ) , current
					return
				}
			}
			return
		}
		parent := filepath.Dir( current )
		if parent == current { return }
		current = parent
	}
}

// conditions are the feature expressions a line sits under, outermost
// first: the file's, then each block it is in.
func ( loaded *pkg ) conditions( name string , line int ) ( result []string ) {
	lines := loaded.text[ name ]
	for index := 0 ; index < len( lines ) && index < 10 ; index++ {
		if match := wholeFileMarker.FindStringSubmatch( lines[ index ] ); match != nil {
			result = append( result , match[ 1 ] )
			break
		}
	}
	stack := []string{}
	for index := 0 ; index < line - 1 && index < len( lines ) ; index++ {
		if match := blockStart.FindStringSubmatch( lines[ index ] ); match != nil {
			stack = append( stack , match[ 1 ] )
		} else if blockEnd.MatchString( lines[ index ] ) && len( stack ) > 0 {
			stack = stack[ : len( stack ) - 1 ]
		}
	}
	result = append( result , stack... )
	if line - 1 < len( lines ) {
		if match := lineMarker.FindStringSubmatch( lines[ line - 1 ] ); match != nil { result = append( result , match[ 1 ] ) }
	}
	return
}

func ( loaded *pkg ) line( position token.Pos ) ( name string , line int ) {
	where := loaded.fset.Position( position )
	name , line = where.Filename , where.Line
	return
}

// featureSwitches are the keys of the map featureGuards answers: the
// features whose routes answer 404 while they are switched off.
func ( loaded *pkg ) featureSwitches() ( switches map[string]bool ) {
	switches = map[string]bool{}
	for _ , name := range loaded.names {
		for _ , decl := range loaded.files[ name ].Decls {
			function , ok := decl.( *ast.FuncDecl )
			if ok == false || function.Name.Name != "featureGuards" || function.Body == nil { continue }
			ast.Inspect( function.Body , func( node ast.Node ) bool {
				literal , ok := node.( *ast.CompositeLit )
				if ok == false { return true }
				if _ , is_map := literal.Type.( *ast.MapType ); is_map == false { return true }
				for _ , element := range literal.Elts {
					pair , ok := element.( *ast.KeyValueExpr )
					if ok == false { continue }
					if key , ok := pair.Key.( *ast.BasicLit ); ok && key.Kind == token.STRING {
						if text , err := strconv.Unquote( key.Value ); err == nil { switches[ text ] = true }
					}
				}
				return false
			} )
		}
	}
	return
}

// Reading the declarations.

// routeStart is the first line of a declaration: // @route(
var routeStart = regexp.MustCompile( `^//[ \t]*@route\(` )

func ( loaded *pkg ) routes( found *problems ) ( routes []*route ) {
	for _ , name := range loaded.names {
		file := loaded.files[ name ]
		claimed := map[*ast.Comment]bool{}
		for _ , decl := range file.Decls {
			function , ok := decl.( *ast.FuncDecl )
			if ok == false || function.Doc == nil { continue }
			start := -1
			for index , comment := range function.Doc.List {
				if routeStart.MatchString( comment.Text ) {
					start = index
					break
				}
			}
			if start < 0 { continue }
			lines := function.Doc.List[ start : ]
			for _ , comment := range lines { claimed[ comment ] = true }
			declared := loaded.read( function , file , lines , found )
			if declared != nil { routes = append( routes , declared ) }
		}
		for _ , group := range file.Comments {
			for _ , comment := range group.List {
				if claimed[ comment ] { continue }
				at , line := loaded.line( comment.Pos() )
				switch {
				case strings.HasPrefix( comment.Text , "//apidoc:" ):
					found.add( at , line , "//apidoc: directives are gone: declare the route with // @route(...), the last thing in its method's doc comment" )
				case routeStart.MatchString( comment.Text ):
					found.add( at , line , "// @route(...) belongs at the end of the doc comment of a route's method on *Handlers" )
				}
			}
		}
	}
	return
}

func ( loaded *pkg ) read( function *ast.FuncDecl , file *ast.File , comments []*ast.Comment , found *problems ) ( declared *route ) {
	name , line := loaded.line( function.Pos() )
	declared = &route{
		handler:    function.Name.Name,
		file:       name,
		line:       line,
		op:         map[string]any{},
		opLines:    map[string]int{},
		requestIn:  file,
		conditions: loaded.conditions( name , line ),
	}
	ok := loaded.signature( function , file , declared , found )
	src := &source{ file: name , found: found }
	texts := []string{}
	for _ , comment := range comments {
		_ , at := loaded.line( comment.Pos() )
		text := strings.TrimPrefix( comment.Text , "//" )
		text = lineMarker.ReplaceAllString( text , "" )
		texts = append( texts , text )
		src.lines = append( src.lines , at )
	}
	src.text = strings.Join( texts , "\n" )
	declared.readDeclaration( src )
	if len( declared.routes ) == 0 && src.failed == false { found.add( name , line , "%s: @route( names no \"METHOD /path\"" , declared.handler ) }
	if ok == false || src.failed { declared = nil }
	return
}

func ( loaded *pkg ) signature( function *ast.FuncDecl , file *ast.File , declared *route , found *problems ) ( ok bool ) {
	name , line := declared.file , declared.line
	wrong := func() {
		found.add( name , line , "%s: a route's method is func ( handlers *Handlers ) %s( c fiber.Ctx , in *In ) ( *Out , error ), or ... error for a route that writes its own reply" , declared.handler , declared.handler )
	}
	receiver := function.Recv
	if receiver == nil || len( receiver.List ) != 1 || exprText( receiver.List[ 0 ].Type ) != "*Handlers" {
		wrong()
		return
	}
	if len( receiver.List[ 0 ].Names ) != 1 || receiver.List[ 0 ].Names[ 0 ].Name != "handlers" {
		found.add( name , line , "%s: name the receiver handlers: the table's guards refer to it" , declared.handler )
		return
	}
	params := flatten( function.Type.Params )
	if len( params ) != 2 || isFiberCtx( params[ 0 ] , file ) == false {
		wrong()
		return
	}
	star , is_pointer := params[ 1 ].( *ast.StarExpr )
	if is_pointer == false {
		wrong()
		return
	}
	declared.request = star.X
	results := flatten( function.Type.Results )
	switch {
	case len( results ) == 1 && exprText( results[ 0 ] ) == "error":
		declared.stream = true
	case len( results ) == 2 && exprText( results[ 1 ] ) == "error":
		if _ , is_pointer := results[ 0 ].( *ast.StarExpr ); is_pointer == false {
			wrong()
			return
		}
	default:
		wrong()
		return
	}
	ok = true
	return
}

func flatten( list *ast.FieldList ) ( types []ast.Expr ) {
	if list == nil { return }
	for _ , entry := range list.List {
		count := len( entry.Names )
		if count == 0 { count = 1 }
		for index := 0 ; index < count ; index++ { types = append( types , entry.Type ) }
	}
	return
}

func isFiberCtx( expr ast.Expr , file *ast.File ) ( ok bool ) {
	selector , is_selector := expr.( *ast.SelectorExpr )
	if is_selector == false || selector.Sel.Name != "Ctx" { return }
	alias , is_ident := selector.X.( *ast.Ident )
	if is_ident == false { return }
	path := importPath( file , alias.Name )
	ok = strings.HasPrefix( path , "github.com/gofiber/fiber/" )
	return
}

func importPath( file *ast.File , alias string ) ( path string ) {
	for _ , spec := range file.Imports {
		value , _ := strconv.Unquote( spec.Path.Value )
		name := value[ strings.LastIndex( value , "/" ) + 1 : ]
		if spec.Name != nil { name = spec.Name.Name }
		if strings.HasPrefix( name , "v" ) && spec.Name == nil {
			if _ , err := strconv.Atoi( name[ 1 : ] ); err == nil {
				trimmed := strings.TrimSuffix( value , "/" + name )
				name = trimmed[ strings.LastIndex( trimmed , "/" ) + 1 : ]
			}
		}
		if name == alias {
			path = value
			return
		}
	}
	return
}

var methods = map[string]bool{ "GET": true , "POST": true , "PUT": true , "PATCH": true , "DELETE": true }

func ( declared *route ) readRoute( where string , line int , found *problems ) {
	parts := strings.Fields( where )
	if len( parts ) != 2 || methods[ parts[ 0 ] ] == false || strings.HasPrefix( parts[ 1 ] , "/" ) == false {
		found.add( declared.file , line , "@route(\"%s\"): give \"METHOD /path\", such as \"POST /api/admin/users/{user_id}/rename\"" , where )
		return
	}
	for _ , segment := range strings.Split( parts[ 1 ] , "/" )[ 1 : ] {
		if strings.ContainsAny( segment , "{}" ) && specParameter.MatchString( segment ) == false {
			found.add( declared.file , line , "path segment %q: a parameter is a whole segment, {name}" , segment )
			return
		}
		if strings.ContainsAny( segment , ":*" ) {
			found.add( declared.file , line , "path segment %q: write parameters as {name}" , segment )
			return
		}
	}
	declared.routes = append( declared.routes , methodPath{ method: parts[ 0 ] , path: parts[ 1 ] , line: line } )
}

