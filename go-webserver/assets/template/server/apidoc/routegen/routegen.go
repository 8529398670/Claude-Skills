// source is a declaration's text, the comment markers and feature markers
// taken off, read like the Python call it is spelled as.
type source struct {
	text   string
	lines  []int // the file's line of each line of text
	at     int
	file   string
	found  *problems
	failed bool
}

func ( src *source ) lineAt( offset int ) ( line int ) {
	if offset > len( src.text ) { offset = len( src.text ) }
	line = src.lines[ strings.Count( src.text[ : offset ] , "\n" ) ]
	return
}

// fail reports the declaration's first mistake; what follows one is not
// worth reading.
func ( src *source ) fail( offset int , format string , args ...any ) {
	if src.failed { return }
	src.failed = true
	src.found.add( src.file , src.lineAt( offset ) , format , args... )
}

func ( src *source ) peek() ( char byte ) {
	if src.at < len( src.text ) { char = src.text[ src.at ] }
	return
}

func ( src *source ) skipSpace() {
	for src.at < len( src.text ) && strings.IndexByte( " \t\r\n" , src.text[ src.at ] ) >= 0 { src.at++ }
}

// readString reads one "string" or 'string', with Python's common escapes.
func ( src *source ) readString() ( value string , ok bool ) {
	start := src.at
	quote := src.peek()
	if quote != '"' && quote != '\'' { return }
	var text strings.Builder
	for src.at++ ; src.at < len( src.text ) ; src.at++ {
		char := src.text[ src.at ]
		switch {
		case char == '\n':
			src.fail( start , "an unfinished string: end it on its line, and go on in another \"...\" on the next" )
			return
		case char == quote:
			src.at++
			value , ok = text.String() , true
			return
		case char == '\\' && src.at + 1 < len( src.text ):
			src.at++
			switch escaped := src.text[ src.at ]; escaped {
			case '\\' , '"' , '\'':
				text.WriteByte( escaped )
			case 'n':
				text.WriteByte( '\n' )
			case 't':
				text.WriteByte( '\t' )
			default:
				src.fail( src.at , "\\%c: a string's escapes are \\\\ \\\" \\' \\n and \\t" , escaped )
				return
			}
		default:
			text.WriteByte( char )
		}
	}
	src.fail( start , "an unfinished string" )
	return
}

// readStrings reads adjacent strings, joined the way Python joins them.
func ( src *source ) readStrings() ( value string , ok bool ) {
	for {
		part , read := src.readString()
		if read == false {
			if src.failed { ok = false }
			return
		}
		value , ok = value + part , true
		save := src.at
		src.skipSpace()
		if quote := src.peek(); quote != '"' && quote != '\'' {
			src.at = save
			return
		}
	}
}

func ( src *source ) readName() ( name string ) {
	start := src.at
	for src.at < len( src.text ) {
		char := src.text[ src.at ]
		if char == '_' || char >= 'a' && char <= 'z' || char >= 'A' && char <= 'Z' || src.at > start && char >= '0' && char <= '9' {
			src.at++
			continue
		}
		break
	}
	name = src.text[ start : src.at ]
	return
}

// readExpression reads Go source up to a , or one of closers outside
// brackets and strings, and checks it is a Go expression.
func ( src *source ) readExpression( key string , closers string ) ( text string , ok bool ) {
	start , depth := src.at , 0
	for ; src.at < len( src.text ) ; src.at++ {
		char := src.text[ src.at ]
		switch {
		case char == '"' || char == '\'' || char == '`':
			end := src.at + 1
			for end < len( src.text ) && src.text[ end ] != char {
				if src.text[ end ] == '\\' && char != '`' { end++ }
				end++
			}
			if end >= len( src.text ) {
				src.fail( src.at , "%s=: an unfinished Go string" , key )
				return
			}
			src.at = end
		case char == '(' || char == '[' || char == '{':
			depth++
		case depth > 0 && ( char == ')' || char == ']' || char == '}' ):
			depth--
		case depth == 0 && ( char == ',' || strings.IndexByte( closers , char ) >= 0 ):
			text = strings.TrimSpace( src.text[ start : src.at ] )
			if text == "" {
				src.fail( start , "%s= needs a Go expression" , key )
				return
			}
			if _ , err := parser.ParseExpr( text ); err != nil {
				src.fail( start , "%s=%s is not a Go expression: %v" , key , text , err )
				return
			}
			ok = true
			return
		}
	}
	src.fail( start , "%s=: the declaration ends before its )" , key )
	return
}

// readDeclaration reads @route("METHOD /path", key=value, ...).
func ( declared *route ) readDeclaration( src *source ) {
	src.skipSpace()
	src.at += len( "@route(" )
	src.skipSpace()
	start := src.at
	where , ok := src.readStrings()
	if ok == false {
		src.fail( start , "@route( starts with where the route is: \"METHOD /path\"" )
		return
	}
	declared.readRoute( where , src.lineAt( start ) , src.found )
	for {
		src.skipSpace()
		if src.peek() == ')' {
			src.at++
			break
		}
		if src.peek() != ',' {
			src.fail( src.at , "@route(...): a , or the closing ) goes here" )
			return
		}
		src.at++
		src.skipSpace()
		if src.peek() == ')' {
			src.at++
			break
		}
		key_at := src.at
		key := src.readName()
		if key == "" {
			src.fail( key_at , "@route(...): key=value goes here (only where the route is comes without a key)" )
			return
		}
		src.skipSpace()
		if src.peek() != '=' {
			src.fail( src.at , "@route(...): %s needs =value" , key )
			return
		}
		src.at++
		src.skipSpace()
		declared.readValue( key , key_at , src )
		if src.failed { return }
	}
	src.skipSpace()
	if src.at < len( src.text ) { src.fail( src.at , "nothing goes after @route(...)'s closing ) in the doc comment" ) }
}

func ( declared *route ) readValue( key string , key_at int , src *source ) {
	line := src.lineAt( key_at )
	kind , is_op := opKeys[ key ]
	values , lines := declared.op , declared.opLines
	if is_op == false {
		tool_kind , is_tool := toolKeys[ key ]
		if is_tool == false {
			names := []string{}
			for name := range opKeys { names = append( names , name ) }
			for name := range toolKeys { names = append( names , name ) }
			sort.Strings( names )
			src.fail( key_at , "@route(...): unknown key %q (%s)" , key , strings.Join( names , ", " ) )
			return
		}
		kind = tool_kind
		if declared.tool == nil { declared.tool = &tool{ values: map[string]any{} , line: line } }
		values , lines = declared.tool.values , map[string]int{}
		if key == "mcp" { declared.tool.line = line }
	}
	if _ , set := values[ key ]; set || key == "use" && declared.uses != nil {
		src.fail( key_at , "@route(...): %s is set twice" , key )
		return
	}
	lines[ key ] = line
	value_at := src.at
	switch kind {
	case stringKey:
		text , ok := src.readStrings()
		if ok == false {
			src.fail( value_at , "%s= is a \"string\"" , key )
			return
		}
		if key == "feature" && featureName.MatchString( text ) == false {
			src.fail( value_at , "feature=%q is not a feature name" , text )
			return
		}
		values[ key ] = text
	case accessKey , roleKey:
		name := src.readName()
		allowed , listed := accessValues , "SIGNED, PUBLIC, SESSION_ONLY or KEY_ONLY"
		if kind == roleKey { allowed , listed = roleValues , "ADMIN or OWNER" }
		value , known := allowed[ name ]
		if known == false {
			src.fail( value_at , "%s=%s (%s)" , key , src.text[ value_at : src.at ] + src.wordAfter() , listed )
			return
		}
		values[ key ] = value
	case statusKey:
		number := src.readNumber()
		status , err := strconv.Atoi( number )
		if err != nil || status < 100 || status > 599 {
			src.fail( value_at , "status=%s is not an HTTP status" , number + src.wordAfter() )
			return
		}
		values[ key ] = status
	case errorsKey:
		if src.peek() != '(' {
			src.fail( value_at , "errors= is a tuple of statuses: (404,) or (404, 409)" )
			return
		}
		src.at++
		statuses := []int{}
		for {
			src.skipSpace()
			if src.peek() == ')' {
				src.at++
				break
			}
			number_at := src.at
			number := src.readNumber()
			status , err := strconv.Atoi( number )
			if err != nil || status < 400 || status > 599 {
				src.fail( number_at , "errors=: %q is not an error status" , number + src.wordAfter() )
				return
			}
			statuses = append( statuses , status )
			src.skipSpace()
			if src.peek() == ',' {
				src.at++
				continue
			}
			if src.peek() != ')' {
				src.fail( src.at , "errors=: a , or ) goes here" )
				return
			}
		}
		if len( statuses ) == 0 {
			src.fail( value_at , "errors=() lists nothing: leave it out" )
			return
		}
		values[ key ] = statuses
	case boolKey:
		switch name := src.readName(); name {
		case "True":
			values[ key ] = true
		case "False":
			values[ key ] = false
		default:
			src.fail( value_at , "%s=%s: write True or False" , key , name + src.wordAfter() )
			return
		}
	case typeKey , exprKey:
		text , ok := src.readExpression( key , ")" )
		if ok == false { return }
		values[ key ] = text
	case useKey:
		if src.peek() != '[' {
			src.fail( value_at , "use= is a list of Go expressions: [sameOrigin( loginElsewhere )]" )
			return
		}
		src.at++
		declared.uses = []string{}
		for {
			src.skipSpace()
			if src.peek() == ']' {
				src.at++
				break
			}
			text , ok := src.readExpression( key , "]" )
			if ok == false { return }
			declared.uses = append( declared.uses , text )
			if src.peek() == ',' { src.at++ }
		}
	}
}

func ( src *source ) readNumber() ( number string ) {
	start := src.at
	for src.at < len( src.text ) && src.text[ src.at ] >= '0' && src.text[ src.at ] <= '9' { src.at++ }
	number = src.text[ start : src.at ]
	return
}

// wordAfter is the rest of a mistaken value, for the message.
func ( src *source ) wordAfter() ( rest string ) {
	end := src.at
	for end < len( src.text ) && strings.IndexByte( " \t\n,)" , src.text[ end ] ) < 0 { end++ }
	rest = src.text[ src.at : end ]
	return
}

// Checking a route against its request type.

func ( loaded *pkg ) check( declared *route , found *problems ) {
	if declared.request == nil { return }
	fields , ok := loaded.fieldsOf( declared.request , declared.requestIn , map[string]bool{} )
	if ok == false {
		found.add( declared.file , declared.line , "%s: cannot read the request type %s" , declared.handler , exprText( declared.request ) )
		return
	}
	declared.fields = fields
	in_path := map[string]bool{}
	for _ , entry := range fields {
		if entry.place == "path" { in_path[ entry.wire ] = true }
	}
	for _ , mounted := range declared.routes {
		named := map[string]bool{}
		for _ , segment := range strings.Split( mounted.path , "/" ) {
			if match := specParameter.FindStringSubmatch( segment ); match != nil {
				named[ match[ 1 ] ] = true
				if in_path[ match[ 1 ] ] == false {
					found.add( declared.file , mounted.line , "{%s} is not a path:\"%s\" field of %s" , match[ 1 ] , match[ 1 ] , exprText( declared.request ) )
				}
			}
		}
		for wire := range in_path {
			if named[ wire ] == false {
				found.add( declared.file , mounted.line , "%s has a path:\"%s\" field that %s does not have" , exprText( declared.request ) , wire , mounted.path )
			}
		}
	}
	op := declared.op
	access , _ := op[ "access" ].( string )
	role , _ := op[ "role" ].( string )
	line := declared.opLines[ "role" ]
	if line == 0 { line = declared.line }
	if role == "Owner" && access != "" && access != "Signed" && access != "SessionOnly" {
		found.add( declared.file , line , "role=OWNER is a browser session: access=%s cannot go with it" , spelled( accessValues , access ) )
	}
	if role != "" && access == "Public" { found.add( declared.file , line , "a PUBLIC route has no role" ) }
	if role == "Owner" && access == "SessionOnly" { found.add( declared.file , line , "role=OWNER is session-only already: leave access out" ) }
	if declared.tool != nil {
		values := declared.tool.values
		name , _ := values[ "mcp" ].( string )
		switch {
		case name == "":
			found.add( declared.file , declared.tool.line , "@route(...): the tool keys (read_only, destructive, admin_only, enabled, call, mcp_note, mcp_title, mcp_description) need mcp=\"tool_name\"" )
		case toolName.MatchString( name ) == false:
			found.add( declared.file , declared.tool.line , "mcp=%q: a tool's name is lower case letters, digits and _" , name )
		}
		title , description := declared.toolTexts()
		if title == "" { found.add( declared.file , declared.tool.line , "mcp=%q: the tool's title is the summary, or mcp_title=: give one" , name ) }
		if description == "" { found.add( declared.file , declared.tool.line , "mcp=%q: the tool's description is the description, then mcp_note, or mcp_description=: give one" , name ) }
		if _ , has := values[ "call" ]; declared.stream && has == false {
			found.add( declared.file , declared.tool.line , "mcp=%q: %s writes its own reply, so its tool needs call=" , name , declared.handler )
		}
	}
}

// toolTexts are the tool's title and description: mcp_title, or else the
// summary, with " (admin)" for an admin-only tool; mcp_description, or else
// the description, then mcp_note.
func ( declared *route ) toolTexts() ( title string , description string ) {
	values := declared.tool.values
	title , _ = values[ "mcp_title" ].( string )
	if title == "" {
		title , _ = declared.op[ "summary" ].( string )
		if title != "" && declared.adminOnly() { title += " (admin)" }
	}
	description , _ = values[ "mcp_description" ].( string )
	if description == "" {
		shared , _ := declared.op[ "description" ].( string )
		note , _ := values[ "mcp_note" ].( string )
		description = strings.TrimSpace( shared + " " + note )
	}
	return
}

// adminOnly is admin_only=, which is on by default for role=ADMIN.
func ( declared *route ) adminOnly() ( admin bool ) {
	admin , set := declared.tool.values[ "admin_only" ].( bool )
	if set == false { admin = declared.op[ "role" ] == "Admin" }
	return
}

// fieldsOf is a struct's JSON fields, through embedded structs, as far as
// the URL is concerned: path and query fields by their URL names.
func ( loaded *pkg ) fieldsOf( expr ast.Expr , file *ast.File , seen map[string]bool ) ( fields []field , ok bool ) {
	spec , found := loaded.lookupType( expr , file )
	if found == false {
		if exprText( expr ) == "apidoc.None" || strings.HasSuffix( exprText( expr ) , ".None" ) && importPathEndsWith( file , expr , "/server/apidoc" ) {
			ok = true
		}
		return
	}
	key := spec.dir + "." + spec.spec.Name.Name
	if seen[ key ] {
		ok = true
		return
	}
	seen[ key ] = true
	structure , is_struct := spec.spec.Type.( *ast.StructType )
	if is_struct == false {
		ok = true
		return
	}
	ok = true
	for _ , entry := range structure.Fields.List {
		tag := reflect.StructTag( "" )
		if entry.Tag != nil {
			unquoted , _ := strconv.Unquote( entry.Tag.Value )
			tag = reflect.StructTag( unquoted )
		}
		json_name , _ , _ := strings.Cut( tag.Get( "json" ) , "," )
		if json_name == "-" { continue }
		if len( entry.Names ) == 0 {
			if json_name == "" {
				inner := entry.Type
				if star , is_pointer := inner.( *ast.StarExpr ); is_pointer { inner = star.X }
				embedded , embedded_ok := spec.pkg.fieldsOf( inner , spec.file , seen )
				if embedded_ok == false {
					ok = false
					return
				}
				fields = append( fields , embedded... )
				continue
			}
		}
		names := []string{}
		for _ , name := range entry.Names {
			if ast.IsExported( name.Name ) { names = append( names , name.Name ) }
		}
		if len( entry.Names ) == 0 { names = append( names , exprText( entry.Type ) ) }
		for _ , name := range names {
			item := field{ name: name }
			if json_name != "" { item.name = json_name }
			for _ , place := range []string{ "path" , "query" } {
				if wire := tag.Get( place ); wire != "" { item.place , item.wire = place , wire }
			}
			fields = append( fields , item )
		}
	}
	return
}

func importPathEndsWith( file *ast.File , expr ast.Expr , suffix string ) ( ok bool ) {
	selector , is_selector := expr.( *ast.SelectorExpr )
	if is_selector == false { return }
	alias , is_ident := selector.X.( *ast.Ident )
	if is_ident == false { return }
	ok = strings.HasSuffix( importPath( file , alias.Name ) , suffix )
	return
}

func ( loaded *pkg ) lookupType( expr ast.Expr , file *ast.File ) ( spec typeSpec , ok bool ) {
	switch typed := expr.( type ) {
	case *ast.Ident:
		spec , ok = loaded.localType( typed.Name )
	case *ast.SelectorExpr:
		alias , is_ident := typed.X.( *ast.Ident )
		if is_ident == false { return }
		path := importPath( file , alias.Name )
		if loaded.module == "" || ( path != loaded.module && strings.HasPrefix( path , loaded.module + "/" ) == false ) { return }
		dir := filepath.Join( loaded.moduleDir , filepath.FromSlash( strings.TrimPrefix( strings.TrimPrefix( path , loaded.module ) , "/" ) ) )
		other := loaded.otherPackage( dir )
		if other == nil { return }
		spec , ok = other.localType( typed.Sel.Name )
	case *ast.IndexExpr:
		spec , ok = loaded.lookupType( typed.X , file )
	}
	return
}

func ( loaded *pkg ) localType( name string ) ( spec typeSpec , ok bool ) {
	for _ , file_name := range loaded.names {
		file := loaded.files[ file_name ]
		for _ , decl := range file.Decls {
			general , is_general := decl.( *ast.GenDecl )
			if is_general == false || general.Tok != token.TYPE { continue }
			for _ , item := range general.Specs {
				type_spec := item.( *ast.TypeSpec )
				if type_spec.Name.Name == name {
					spec , ok = typeSpec{ spec: type_spec , file: file , pkg: loaded , dir: loaded.dir } , true
					return
				}
			}
		}
	}
	return
}

// otherPackage is another package of the module, read for its types.
func ( loaded *pkg ) otherPackage( dir string ) ( other *pkg ) {
	if cached , found := loaded.external[ dir ]; found {
		if cached == nil { return }
		other = cached.pkgRef
		return
	}
	other = &pkg{ dir: dir , fset: loaded.fset , files: map[string]*ast.File{} , text: map[string][]string{} , module: loaded.module , moduleDir: loaded.moduleDir , external: loaded.external }
	entries , err := os.ReadDir( dir )
	if err != nil {
		loaded.external[ dir ] = nil
		other = nil
		return
	}
	for _ , entry := range entries {
		name := entry.Name()
		if entry.IsDir() || strings.HasSuffix( name , ".go" ) == false || strings.HasSuffix( name , "_test.go" ) { continue }
		file , parse_err := parser.ParseFile( loaded.fset , filepath.Join( dir , name ) , nil , parser.ParseComments )
		if parse_err != nil { continue }
		other.files[ name ] = file
		other.names = append( other.names , name )
	}
	sort.Strings( other.names )
	loaded.external[ dir ] = &external{ pkgRef: other }
	return
}

func exprText( expr ast.Expr ) ( text string ) {
	var buffer bytes.Buffer
	writeExpr( &buffer , expr )
	text = buffer.String()
	return
}

func writeExpr( buffer *bytes.Buffer , expr ast.Expr ) {
	switch typed := expr.( type ) {
	case *ast.Ident:
		buffer.WriteString( typed.Name )
	case *ast.StarExpr:
		buffer.WriteString( "*" )
		writeExpr( buffer , typed.X )
	case *ast.SelectorExpr:
		writeExpr( buffer , typed.X )
		buffer.WriteString( "." + typed.Sel.Name )
	case *ast.IndexExpr:
		writeExpr( buffer , typed.X )
		buffer.WriteString( "[" )
		writeExpr( buffer , typed.Index )
		buffer.WriteString( "]" )
	default:
		buffer.WriteString( fmt.Sprintf( "%T" , expr ) )
	}
}

// The order routes are mounted in: at the first segment where two differ,
// a literal before a {param}, then literals in order; a shorter path before
// a longer one it starts; then by method.

type mounted struct {
	declared *route
	method   string
	path     string
	line     int
}

func segments( path string ) ( result []string ) {
	result = strings.Split( strings.Trim( path , "/" ) , "/" )
	if len( result ) == 1 && result[ 0 ] == "" { result = nil }
	return
}

func isParameter( segment string ) ( ok bool ) {
	ok = specParameter.MatchString( segment )
	return
}

func before( a mounted , b mounted ) ( less bool ) {
	left , right := segments( a.path ) , segments( b.path )
	for index := 0 ; index < len( left ) && index < len( right ) ; index++ {
		l_param , r_param := isParameter( left[ index ] ) , isParameter( right[ index ] )
		if l_param != r_param { return r_param }
		if l_param { continue }
		if left[ index ] != right[ index ] { return left[ index ] < right[ index ] }
	}
	if len( left ) != len( right ) { return len( left ) < len( right ) }
	if a.path != b.path { return a.path < b.path }
	return a.method < b.method
}

// ambiguous is true when one URL could match both with neither the more
// specific: each has a literal where the other has a {param}.
func ambiguous( a mounted , b mounted ) ( result bool ) {
	if a.method != b.method { return }
	left , right := segments( a.path ) , segments( b.path )
	if len( left ) != len( right ) { return }
	left_wins , right_wins := false , false
	for index := range left {
		l_param , r_param := isParameter( left[ index ] ) , isParameter( right[ index ] )
		switch {
		case l_param == false && r_param == false && left[ index ] != right[ index ]:
			return false
		case l_param == false && r_param:
			left_wins = true
		case l_param && r_param == false:
			right_wins = true
		}
	}
	result = left_wins == right_wins
	return
}

func order( routes []*route , found *problems ) ( ordered []mounted ) {
	for _ , declared := range routes {
		for _ , entry := range declared.routes {
			ordered = append( ordered , mounted{ declared: declared , method: entry.method , path: entry.path , line: entry.line } )
		}
	}
	sort.SliceStable( ordered , func( a , b int ) bool { return before( ordered[ a ] , ordered[ b ] ) } )
	for a := 0 ; a < len( ordered ) ; a++ {
		for b := a + 1 ; b < len( ordered ) ; b++ {
			if ambiguous( ordered[ a ] , ordered[ b ] ) {
				found.add( ordered[ b ].declared.file , ordered[ b ].line , "%s %s and %s %s (%s:%d) can match the same request" ,
					ordered[ b ].method , ordered[ b ].path , ordered[ a ].method , ordered[ a ].path , ordered[ a ].declared.file , ordered[ a ].line )
			}
		}
	}
	return
}

// Guards and statuses.

func ( declared *route ) guards( switches map[string]bool ) ( guards []string , statuses []int ) {
	op := declared.op
	access , _ := op[ "access" ].( string )
	role , _ := op[ "role" ].( string )
	feature , _ := op[ "feature" ].( string )
	no_switch , _ := op[ "no_switch" ].( bool )
	add := func( statuses_of ...int ) { statuses = append( statuses , statuses_of... ) }
	if switches[ feature ] && no_switch == false {
		guards = append( guards , "handlers.featureGuards()[ " + strconv.Quote( feature ) + " ]" )
		add( 404 )
	}
	who := ""
	switch {
	case access == "Public":
	case access == "KeyOnly":
		who = requireAPIKey
	case role == "Admin":
		who = requireAdmin
	case role == "Owner":
		who = requireOwner
	default:
		who = requireLogin
	}
	if who != "" {
		guards = append( guards , who )
		add( guardStatuses[ who ]... )
	}
	if access == "KeyOnly" && role == "Admin" {
		guards = append( guards , requireAdmin )
		add( guardStatuses[ requireAdmin ]... )
	}
	if access == "SessionOnly" && role != "Owner" {
		guards = append( guards , requireSession )
		add( guardStatuses[ requireSession ]... )
	}
	for _ , use := range declared.uses {
		guards = append( guards , use )
		called , _ , _ := strings.Cut( use , "(" )
		add( guardStatuses[ strings.TrimSpace( called ) ]... )
		if strings.HasPrefix( use , "handlers.featureGuards()[" ) { add( 404 ) }
	}
	return
}

// errors are the statuses the docs list: the guards', the request checks'
// and the handler's own.
func ( declared *route ) errors( method string , switches map[string]bool ) ( result []int ) {
	_ , statuses := declared.guards( switches )
	op := declared.op
	access , _ := op[ "access" ].( string )
	no_csrf , _ := op[ "no_csrf" ].( bool )
	_ , raw_body := op[ "raw_body" ]
	csrf := method != "GET" && access != "Public" && no_csrf == false && raw_body == false
	if csrf { statuses = append( statuses , 400 , 403 ) }
	if len( declared.fields ) > 0 { statuses = append( statuses , 400 ) }
	if own , ok := op[ "errors" ].( []int ); ok { statuses = append( statuses , own... ) }
	seen := map[int]bool{}
	for _ , status := range statuses {
		if seen[ status ] == false {
			seen[ status ] = true
			result = append( result , status )
		}
	}
	sort.Ints( result )
	return
}

// Writing the file.

func ( loaded *pkg ) write( ordered []mounted , routes []*route , switches map[string]bool , found *problems ) ( source []byte ) {
	out := &bytes.Buffer{}
	generating := loaded.files[ loaded.generating ]
	imports := map[string]string{}
	for _ , spec := range generating.Imports {
		path , _ := strconv.Unquote( spec.Path.Value )
		_ , line := loaded.line( spec.Pos() )
		text := strings.TrimSpace( loaded.text[ loaded.generating ][ line - 1 ] )
		switch {
		case strings.HasPrefix( path , "github.com/gofiber/fiber/" ):
			imports[ "fiber" ] = text
		case strings.HasSuffix( path , "/server/apidoc" ):
			imports[ "apidoc" ] = text
		case strings.HasSuffix( path , "/server/mcp" ):
			imports[ "mcp" ] = text
		}
	}
	for _ , needed := range []string{ "fiber" , "apidoc" } {
		if imports[ needed ] == "" { found.add( loaded.generating , 1 , "it imports no %s package for the generated table to use" , needed ) }
	}
	tools := []*route{}
	for _ , declared := range routes {
		if declared.tool != nil { tools = append( tools , declared ) }
	}
	sort.SliceStable( tools , func( a , b int ) bool { return tools[ a ].tool.values[ "mcp" ].( string ) < tools[ b ].tool.values[ "mcp" ].( string ) } )
	if len( tools ) > 0 && imports[ "mcp" ] == "" {
		found.add( tools[ 0 ].file , tools[ 0 ].tool.line , "mcp=: %s imports no mcp package" , loaded.generating )
	}
	mcp_conditions := []string{}
	if text := imports[ "mcp" ]; text != "" {
		if match := lineMarker.FindStringSubmatch( text ); match != nil { mcp_conditions = append( mcp_conditions , match[ 1 ] ) }
	}
	fmt.Fprintf( out , "%s\n\npackage %s\n\nimport (\n" , Header , generating.Name.Name )
	fmt.Fprintf( out , "\t%s\n\n\t%s\n" , imports[ "fiber" ] , imports[ "apidoc" ] )
	if imports[ "mcp" ] != "" { fmt.Fprintf( out , "\t%s\n" , imports[ "mcp" ] ) }
	out.WriteString( ")\n\n" )
	out.WriteString( "// mountDeclared mounts every route declared with @route(...), the most\n" )
	out.WriteString( "// specific path first, behind the guards its declaration implies.\n" )
	out.WriteString( "func ( handlers *Handlers ) mountDeclared( app *fiber.App ) {\n" )
	blocks := &guarded{ out: out , indent: "\t" }
	for _ , entry := range ordered {
		declared := entry.declared
		guards , _ := declared.guards( switches )
		mount := "Mount"
		if declared.stream { mount = "MountStream" }
		var call bytes.Buffer
		fmt.Fprintf( &call , "apidoc.%s( app , %q , %q , %s , handlers.%s" , mount , entry.method , entry.path , declared.opLiteral( entry.method , switches , "\t" ) , declared.handler )
		for _ , guard := range guards { fmt.Fprintf( &call , " , %s" , guard ) }
		call.WriteString( " )" )
		blocks.write( declared.conditions , call.String() )
	}
	blocks.closeTo( 0 )
	out.WriteString( "}\n" )
	if imports[ "mcp" ] != "" {
		// The blank line goes inside the block, so cutting the block leaves
		// the file ending as the source without it would.
		for _ , condition := range mcp_conditions { fmt.Fprintf( out , "// >>> feature:%s\n" , condition ) }
		out.WriteString( "\n" )
		out.WriteString( "// registerDeclaredTools registers the MCP tool of every route whose\n" )
		out.WriteString( "// @route(...) has mcp=, by tool name.\n" )
		out.WriteString( "func ( handlers *Handlers ) registerDeclaredTools( server *mcp.Server ) {\n" )
		blocks := &guarded{ out: out , indent: "\t" }
		for _ , declared := range tools {
			entry := declared.routes[ 0 ]
			for_route := "ForRoute"
			if declared.stream { for_route = "ForStream" }
			call := "nil"
			if text , ok := declared.tool.values[ "call" ].( string ); ok { call = text }
			text := fmt.Sprintf( "server.Register( mcp.%s( %q , handlers.%s , %s , %s ) )" , for_route , entry.method + " " + entry.path , declared.handler , declared.toolLiteral( "\t" ) , call )
			blocks.write( declared.conditions , text )
		}
		blocks.closeTo( 0 )
		out.WriteString( "}\n" )
		for index := len( mcp_conditions ) - 1 ; index >= 0 ; index-- { fmt.Fprintf( out , "// <<< feature:%s\n" , mcp_conditions[ index ] ) }
	}
	source = out.Bytes()
	return
}

// guarded writes entries inside the feature blocks of their handlers,
// keeping a block open across entries that share it.
type guarded struct {
	out    *bytes.Buffer
	indent string
	open   []string
}

func ( blocks *guarded ) write( conditions []string , text string ) {
	common := 0
	for common < len( blocks.open ) && common < len( conditions ) && blocks.open[ common ] == conditions[ common ] { common++ }
	blocks.closeTo( common )
	for _ , condition := range conditions[ common : ] {
		fmt.Fprintf( blocks.out , "%s// >>> feature:%s\n" , blocks.indent , condition )
		blocks.open = append( blocks.open , condition )
	}
	fmt.Fprintf( blocks.out , "%s%s\n" , blocks.indent , text )
}

func ( blocks *guarded ) closeTo( depth int ) {
	for len( blocks.open ) > depth {
		fmt.Fprintf( blocks.out , "%s// <<< feature:%s\n" , blocks.indent , blocks.open[ len( blocks.open ) - 1 ] )
		blocks.open = blocks.open[ : len( blocks.open ) - 1 ]
	}
}

func ( declared *route ) opLiteral( method string , switches map[string]bool , indent string ) ( text string ) {
	op := declared.op
	lines := []string{}
	add := func( name string , value string ) { lines = append( lines , indent + "\t" + name + ": " + value + "," ) }
	for _ , key := range []struct{ name , field string }{
		{ "summary" , "Summary" } , { "description" , "Description" } , { "tag" , "Tag" },
	} {
		if value , ok := op[ key.name ].( string ); ok { add( key.field , strconv.Quote( value ) ) }
	}
	if value , ok := op[ "access" ].( string ); ok && value != "Signed" { add( "Access" , "apidoc." + value ) }
	if op[ "role" ] == "Owner" { add( "Access" , "apidoc.SessionOnly" ) }
	if value , ok := op[ "role" ].( string ); ok { add( "Role" , "apidoc." + value ) }
	if value , ok := op[ "feature" ].( string ); ok { add( "Feature" , strconv.Quote( value ) ) }
	if value , ok := op[ "mcp_http" ].( string ); ok { add( "MCPHTTP" , strconv.Quote( value ) ) }
	if value , ok := op[ "no_csrf" ].( bool ); ok && value { add( "NoCSRF" , "true" ) }
	if value , ok := op[ "raw_body" ].( string ); ok { add( "RawBody" , value + "{}" ) }
	if value , ok := op[ "body_type" ].( string ); ok { add( "BodyType" , strconv.Quote( value ) ) }
	if value , ok := op[ "status" ].( int ); ok { add( "Status" , strconv.Itoa( value ) ) }
	if value , ok := op[ "reply_type" ].( string ); ok { add( "ReplyType" , strconv.Quote( value ) ) }
	if value , ok := op[ "reply_description" ].( string ); ok { add( "ReplyDescription" , strconv.Quote( value ) ) }
	if statuses := declared.errors( method , switches ); len( statuses ) > 0 {
		parts := []string{}
		for _ , status := range statuses { parts = append( parts , strconv.Itoa( status ) ) }
		add( "Errors" , "[]int{ " + strings.Join( parts , " , " ) + " }" )
	}
	text = "apidoc.Op{\n" + strings.Join( lines , "\n" ) + "\n" + indent + "}"
	return
}

func ( declared *route ) toolLiteral( indent string ) ( text string ) {
	values := declared.tool.values
	lines := []string{}
	add := func( name string , value string ) { lines = append( lines , indent + "\t" + name + ": " + value + "," ) }
	title , description := declared.toolTexts()
	add( "Name" , strconv.Quote( values[ "mcp" ].( string ) ) )
	add( "Title" , strconv.Quote( title ) )
	add( "Description" , strconv.Quote( description ) )
	if value , _ := values[ "read_only" ].( bool ); value { add( "ReadOnly" , "true" ) }
	if value , _ := values[ "destructive" ].( bool ); value { add( "Destructive" , "true" ) }
	if declared.adminOnly() { add( "AdminOnly" , "true" ) }
	if value , ok := values[ "enabled" ].( string ); ok { add( "Enabled" , value ) }
	text = "mcp.Tool{\n" + strings.Join( lines , "\n" ) + "\n" + indent + "}"
	return
}
