// Package routegen writes server/routes/routes_generated.go from the
// @route(...) declarations of the route handlers. go generate runs it
// (through server/apidoc/gen), and so does scripts/api_docs.sh; a test in
// server/routes fails while the file is not what it would write.
//
// A route is a method on *Handlers, and the last thing in its doc comment is
// its declaration, spelled exactly like the Python template's @route(...)
// decorator. The doc comment above it is for developers and never reaches
// the docs:
//
//	// cancelLoginLink stops an account's live login link working.
//	//
//	// @route("POST /api/admin/users/{user_id}/cancel-login-link", summary="Stop an account's login link working",
//	//     tag="Admin", role=ADMIN, errors=(404,),
//	//     description="Void an account's live login link without making a new one: a link that went "
//	//         "somewhere it should not have.",
//	//     mcp_note="Devices it already signed in stay signed in; admin_revoke_access ends those too.",  // feature:mcp
//	//     mcp="admin_cancel_login_link", destructive=True,  // feature:mcp
//	// )
//	func ( handlers *Handlers ) cancelLoginLink( c fiber.Ctx , in *userIDPath ) ( reply *cancelLoginLinkReply , err error )
//
// The first argument is where the route is, "METHOD /path", the path as the
// spec writes it ({user_id}): every {param} must be a path:"..." field of the
// request type, and every path field must be in the path. Then keys, in any
// order, each once:
//
//   - apidoc.Op's fields: summary, description, tag, access (SIGNED, the
//     default, PUBLIC, SESSION_ONLY or KEY_ONLY), role (ADMIN or OWNER: the
//     owner from a browser session, so SESSION_ONLY too), feature, mcp_http,
//     status, errors, reply_description, body_type, reply_type, no_csrf and
//     raw_body (a Go type); and no_switch=True, for a route that answers even
//     while its feature is switched off.
//   - use: more middleware, a list of Go expressions copied as they are into
//     the route table, after the guards the declaration implies.
//   - mcp="tool_name" gives the route an MCP tool, and the keys that mean
//     something only with it: read_only, destructive, admin_only (on by
//     default for role=ADMIN), and the Go expressions enabled (a func() bool)
//     and call (a function that makes the tool's answer, given the call, the
//     checked request and, for a JSON route, the route's handler). The tool's
//     title is the summary, with " (admin)" for an admin-only tool, and its
//     description is the description, then mcp_note: words only the tool
//     shows. mcp_title and mcp_description replace them, for a tool whose
//     words must differ from its route's.
//
// The values are Python's: "strings" (adjacent ones are joined, so long text
// wraps), True and False, tuples such as errors=(404, 409), lists such as
// use=[...]. Go expressions (use, call, enabled, raw_body) stay Go. A
// trailing // feature:x marker on a line is not part of it: in the template
// every tool line carries // feature:mcp, so pruning mcp cuts exactly those.
// A declaration longer than a line ends with ) on a line of its own.
// Nothing goes after it in the doc comment. An unknown key, a bad value or
// a key set twice stops the generator, by file and line, and so do the old
// //apidoc: directives.
//
// The method is ( c fiber.Ctx , in *In ) ( *Out , error ) for a JSON reply,
// or ( c fiber.Ctx , in *In ) error for a route that writes its own.
//
// The guards come from the declaration, in this order: the feature's switch
// (from featureGuards in the package, when the feature has one), then who may
// call it (RequireLogin, RequireAdmin, RequireOwner or RequireAPIKey), then
// RequireSession for SESSION_ONLY, then the use expressions. The error
// statuses the docs list follow from the same facts, so errors= lists only
// what the handler itself answers.
